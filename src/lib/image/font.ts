const FALLBACK = GLYPHS[' '] as readonly string[];

const glyphFor = (character: string): readonly string[] =>
  GLYPHS[character.toUpperCase()] ?? FALLBACK;

/** Pixel width of `text` once drawn, so callers can right-align or centre it. */
export const textWidth = (text: string, scale = 1): number =>
  text.length === 0 ? 0 : (text.length * (GLYPH_WIDTH + GLYPH_SPACING) - GLYPH_SPACING) * scale;

export const textHeight = (scale = 1): number => GLYPH_HEIGHT * scale;

/** Draws `text` with its top-left corner at `x, y`. */
export const drawText = (
  canvas: Canvas,
  text: string,
  x: number,
  y: number,
  colour: Colour,
  scale = 1,
): void => {
  let cursor = Math.round(x);

  for (const character of text) {
    const glyph = glyphFor(character);

    for (const [row, bits] of glyph.entries()) {
      for (const [column, bit] of [...bits].entries()) {
        if (bit === '#') {
          canvas.rect(cursor + column * scale, Math.round(y) + row * scale, scale, scale, colour);
        }
      }
    }

    cursor += (GLYPH_WIDTH + GLYPH_SPACING) * scale;
  }
};
